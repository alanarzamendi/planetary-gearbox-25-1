def font(color=BLACK, bold=False, size=10, italic=False):
    return Font(name=F, color=color, bold=bold, size=size, italic=italic)


def header(ws, row, titles, widths=None):
    for j, t in enumerate(titles, 1):
        c = ws.cell(row=row, column=j, value=t)
        c.font = Font(name=F, bold=True, color="FFFFFF", size=10)
        c.fill = HDR_FILL
        c.alignment = Alignment(wrap_text=True, vertical="center")
        c.border = BOX
    if widths:
        for j, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(j)].width = w
    ws.row_dimensions[row].height = 32


def put(ws, row, col, value, color=BLACK, bold=False, fmt=None, wrap=True, fill=None):
    c = ws.cell(row=row, column=col, value=value)
    c.font = font(color, bold)
    c.alignment = Alignment(wrap_text=wrap, vertical="top")
    c.border = BOX
    if fmt:
        c.number_format = fmt
    if fill:
        c.fill = fill
    return c


