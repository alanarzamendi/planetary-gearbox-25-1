def variant(rows):
    out = []
    for g, item, pn, q, hc, ic, k, q1, q2, q3, n, note in rows:
        if pn == "PG25-206":
            q, n, note = 0, 0, "Eliminated (C2): gas-nitrided cage thrust faces."
        elif pn in ("PG25-204", "PG25-306"):
            q, n, note = 0, 0, "Eliminated (C1): one-piece cage, planets inserted radially between the bridges."
        elif item.startswith("Cage screw") or item.startswith("Low-head screw"):
            q, note = 0, "Eliminated with the bolted plate (C1)."
        elif pn == "PG25-205":
            item, note = "One-piece cage 1, windows milled, spline hub (base)", "C1: pin bores line-bored through both walls in one set-up."
        elif pn == "PG25-305":
            item, note = "One-piece output cage with integral shaft (base)", "C1."
        elif pn == "PG25-502":
            q, n, note = 0, 0, "Eliminated (C3): ring 1 lengthened by 12 mm."
        elif pn == "PG25-201":
            item = "Ring gear 1 with integral spacer, over stage 1 planets"
        elif pn == "DIN 5406":
            q, note = 0, "Eliminated (C7): self-locking nut."
        elif item.startswith("Lock nut"):
            item, pn, note = "Self-locking nut KMK 6, tightened", "KMK 6", "C7: integral locking screw."
        elif item.startswith("Bend lock"):
            q, note = 0, "Eliminated with the lock washer (C7)."
        elif item.startswith("Anaerobic"):
            q, note = 3, "One joint fewer (C3)."
        out.append((g, item, pn, q, hc, ic, k, q1, q2, q3, n, note))
    return out


def dfma_sheet(name, rows, title):
    s = wb.create_sheet(name)
    s.cell(row=1, column=1, value=title).font = font(bold=True, size=12)
    cols = ["#", "Group", "Item / operation", "Part no. / standard", "Qty N", "Row type", "Handling code", "t_h per item [s]",
            "Insertion code", "t_i per item [s]", "Operation time [s]", "Q1 moves?", "Q2 different material?",
            "Q3 separate for assembly / service?", "N_min", "Note"]
    header(s, 3, cols, [5, 16, 42, 15, 7, 11, 9, 9, 9, 9, 11, 8, 10, 12, 7, 52])
    r0 = 4
    for i, (g, item, pn, q, hc, ic, k, q1, q2, q3, n, note) in enumerate(rows):
        r = r0 + i
        put(s, r, 1, i + 1)
        put(s, r, 2, g)
        put(s, r, 3, item)
        put(s, r, 4, pn)
        put(s, r, 5, q, BLUE, fmt="0")
        put(s, r, 6, k, BLUE)
        put(s, r, 7, hc, BLUE)
        put(s, r, 8, f"=INDEX('B-D times'!$B$2:$B${BD_LAST},MATCH(G{r},'B-D times'!$A$2:$A${BD_LAST},0))", GREEN, fmt="0.00")
        put(s, r, 9, ic, BLUE)
        put(s, r, 10, f"=INDEX('B-D times'!$B$2:$B${BD_LAST},MATCH(I{r},'B-D times'!$A$2:$A${BD_LAST},0))", GREEN, fmt="0.00")
        put(s, r, 11, f"=E{r}*(H{r}+J{r})", fmt="0.0")
        put(s, r, 12, q1, BLUE)
        put(s, r, 13, q2, BLUE)
        put(s, r, 14, q3, BLUE)
        put(s, r, 15, n, BLUE, fmt="0")
        put(s, r, 16, note)
    rl = r0 + len(rows) - 1
    t = rl + 2
    # summary: labels in column C, values in column E (rows t .. t+6)
    summary = [
        ("Total parts", f'=SUMIF(F{r0}:F{rl},"Part",E{r0}:E{rl})', "0"),
        ("Part line items (rows with qty > 0)", f'=COUNTIFS(F{r0}:F{rl},"Part",E{r0}:E{rl},">0")', "0"),
        ("Separate operations (count)", f'=SUMIF(F{r0}:F{rl},"Operation",E{r0}:E{rl})', "0"),
        ("Total manual assembly time [s]", f"=SUM(K{r0}:K{rl})", "0.0"),
        ("Theoretical minimum part count N_min", f"=SUM(O{r0}:O{rl})", "0"),
        ("Design efficiency E = 3 N_min / time", f"=3*E{t + 4}/E{t + 3}", "0.0%"),
        ("Candidates for elimination (parts - N_min)", f"=E{t}-E{t + 4}", "0"),
    ]
    for j, (lab, fml, fmt) in enumerate(summary):
        put(s, t + j, 3, lab, bold=True, fill=TOT_FILL)
        put(s, t + j, 5, fml, bold=True, fmt=fmt, fill=KEY_FILL if j in (0, 3, 5) else TOT_FILL)
    s.freeze_panes = "D4"
    return s, t


